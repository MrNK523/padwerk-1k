export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const CELL_W = 6;
export const CELL_H = 8;

/** Zeilen-Bitmasken pro Zeichen; Bit 4 = linkes Pixel. */
export const FONT: ReadonlyMap<string, Uint8Array> = (() => {
  const map = new Map<string, Uint8Array>();
  for (const [ch, def] of Object.entries(GLYPHS)) {
    const rows = def.split('|');
    if (rows.length !== GLYPH_H || rows.some((r) => r.length !== GLYPH_W)) {
      throw new Error(`Glyphe '${ch}' hat falsches Format`);
    }
    map.set(ch, Uint8Array.from(rows, (r) => [...r].reduce((acc, c) => (acc << 1) | (c === '#' ? 1 : 0), 0)));
  }
  return map;
})();

const FALLBACK = FONT.get('?')!;

export function glyph(ch: string): Uint8Array {
  return FONT.get(ch) ?? FALLBACK;
}
